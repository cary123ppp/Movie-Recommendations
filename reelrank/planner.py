"""Free-form script  ->  episode YAML (the editable edit plan)."""
import re
from pathlib import Path
import yaml
from . import llm

SYSTEM = """You turn a YouTube/TikTok movie-ranking script into structured JSON for an automated video editor.
Rules:
- NEVER rewrite, shorten or "improve" the narration. Copy the author's words verbatim; you only split them.
- Identify every ranked film: its exact English title and release year (use your knowledge; the year disambiguates remakes).
- Order films as they appear in the video (usually countdown: highest number first, #1 last). rank = the number in the countdown.
- "hook" = narration before the first film. "outro" = narration after the last film. Leave vo empty ("") if the script has none.
- A film's "vo" is everything said about that film, including the "Number X. Title." line, verbatim.
- The author may mark original movie audio with [ORIGINAL: some line] (or [原声: ...]). Remove the marker from vo and report it in
  that film's "originals" as {"quote": the line, "after_sentence": N} where N = how many sentences of that film's vo come before it
  (0 = before the narration starts is NOT allowed; use at least 2). A marker before the first film goes to "cold_open".
- Also write short on-screen card text (English, title case or caps as shown), never more words than the limits:
  hook.overline (3-5 words, e.g. "War Movies That Feel"), hook.headline (1-3 words, the punchline, e.g. "TOO REAL"),
  hook.left / hook.right: two lines each, e.g. ["FOUR FILMS", "RANKED BY INTENSITY"], ["INSPIRED BY", "REAL BATTLES"] (max 3 words per line),
  outro.question: two lines, e.g. ["Which One", "HIT YOU HARDEST?"].
- slug: short snake_case name for the file.
Return JSON only, shaped exactly like:
{"slug": str, "hook": {"overline": str, "headline": str, "left": [str, str], "right": [str, str], "vo": str},
 "cold_open": {"quote": str} or null,
 "films": [{"rank": int, "title": str, "year": int, "vo": str, "originals": [{"quote": str, "after_sentence": int}]}],
 "outro": {"question": [str, str], "vo": str}}"""


def parse_script(cfg, text):
    data = llm.chat_json(cfg, SYSTEM, "Script:\n\n" + text.strip(), temperature=0.1)
    films = data.get("films") or []
    if not films: raise SystemExit("DeepSeek found no films in the script")
    for f in films:
        f["vo"] = re.sub(r"\s*\[(?:ORIGINAL|原声)\s*[:：][^\]]*\]\s*", " ", f.get("vo", "")).strip()
        f["originals"] = [o for o in (f.get("originals") or []) if o.get("quote")]
    return data


def write_episode(data, out_path):
    """Pretty, comment-friendly YAML the user can edit before building."""
    ep = dict(slug=data.get("slug") or Path(out_path).stem, hook=data.get("hook") or {})
    ep["cold_open"] = data.get("cold_open") or False
    ep["films"] = []
    for f in data["films"]:
        e = dict(rank=int(f["rank"]), title=f["title"], year=int(f.get("year") or 0) or None, vo=f["vo"])
        if "originals" in f: e["originals"] = f["originals"]
        if f.get("fact"): e["fact"] = f["fact"]
        ep["films"].append({k: v for k, v in e.items() if v is not None})
    ep["outro"] = data.get("outro") or {}
    head = ("# Edit plan generated by `reelrank plan`. Review it, change anything, then run build.\n"
            "# originals: movie-audio moments. 'at' = seconds in the trailer, 'after_sentence' = where it goes in the narration.\n"
            "# Delete an entry to drop it, or change its quote and remove 'at' to let the program search the trailer again.\n\n")
    Path(out_path).write_text(head + yaml.safe_dump(ep, sort_keys=False, allow_unicode=True, width=140), encoding="utf-8")
    return out_path
